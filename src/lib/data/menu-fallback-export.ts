import {
  categoryTranslationsFromRow,
  itemTranslationsFromRow,
  MENU_TRANSLATION_LANGS,
  variantTranslationsFromRow,
} from "@/lib/menu-translations";
import { getPublicMenu, type MenuCategoryDto, type MenuItemDto, type MenuPayload } from "./menu";
import type { MenuFallback, MenuFallbackSettings } from "./menu-fallback";
import type { Db } from "./types";

/**
 * T-037: builds the break-glass menu snapshot (src/data/menu-fallback.json, read by getFallbackMenu) from the LIVE
 * public menu. Used by scripts/export-menu-fallback.ts (`pnpm menu:export-fallback`); runbook:
 * engineering/ops/menu-fallback.md. Not imported by the app itself.
 *
 * Privacy rule: the JSON ships inside the browser bundle, so it may hold public menu data only.
 * - Read path: `getPublicMenu` with the ANON client (RLS: visible rows; settings from the `public_settings` view,
 *   five display columns). It never touches `site_settings`, `order_rules`, products or stock.
 * - Write path: every field is copied through an explicit allow-list (never a spread of a row or payload), and
 *   `assertOnlyAllowedKeys` refuses the snapshot if any other key appears anywhere in it.
 *
 * Content decisions (break-glass = the database is unreachable, so the page says "ask staff"):
 * - Images are stripped (`imageUrl: null`, `imageVariants: []`): they live in the same Supabase project that is
 *   down, so they would only render as broken images. The menu design supports text-only items.
 * - Sold-out flags are reset to false: sold-out is a same-day state, and the snapshot may be days old.
 * - Specials are left out (time-bound) and the announcement is null (it may be stale).
 * - Translations (api-contract 1.4.0) are kept: they are public menu text, and the break-glass menu should still
 *   show a guest's language. They are rebuilt key by key by the same allow-list sanitizers the read uses
 *   (src/lib/menu-translations.ts): only ne/zh/ja/ko/pt, only name/description/pronunciation/label, strings only.
 */

export const FALLBACK_NOTE =
  "Break-glass menu snapshot, shown only when the live menu cannot load. Generated by `pnpm menu:export-fallback` " +
  "(scripts/export-menu-fallback.ts). Public menu data only. Do not edit by hand.";

export class FallbackExportError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "FallbackExportError";
  }
}

export type FallbackStats = { categories: number; items: number; variants: number };

const DAYS = ["0", "1", "2", "3", "4", "5", "6"] as const;

function pickSettings(s: MenuPayload["settings"]): MenuFallbackSettings {
  const weekly = Object.fromEntries(
    DAYS.map((day) => {
      const ranges = s.hours?.weekly?.[day];
      return [day, Array.isArray(ranges) ? ranges.map((r) => ({ open: String(r.open), close: String(r.close) })) : null];
    }),
  ) as MenuFallbackSettings["hours"]["weekly"];
  const closures = (s.hours?.closures ?? []).map((c) => ({ date: String(c.date), label: String(c.label) }));
  return {
    hours: { weekly, closures },
    announcement: null,
    pricesIncludeVat: s.pricesIncludeVat === true,
    serviceChargePct: Number(s.serviceChargePct) || 0,
    vatPct: 13,
  };
}

function pickItem(it: MenuItemDto): MenuItemDto {
  return {
    id: it.id,
    categoryId: it.categoryId,
    name: it.name,
    description: it.description || null,
    price: it.price,
    diet: it.diet,
    tags: [...(it.tags ?? [])],
    isSoldOut: false,
    imageUrl: null,
    imageVariants: [],
    variants: it.variants.map((v) => ({
      id: v.id,
      kind: v.kind,
      label: v.label,
      priceDelta: v.priceDelta,
      isSoldOut: false,
      translations: variantTranslationsFromRow(v.translations),
    })),
    sortOrder: it.sortOrder,
    translations: itemTranslationsFromRow(it.translations),
  };
}

function pickCategory(c: MenuCategoryDto): MenuCategoryDto {
  return {
    id: c.id,
    slug: c.slug,
    name: c.name,
    sortOrder: c.sortOrder,
    translations: categoryTranslationsFromRow(c.translations),
    items: c.items.map(pickItem),
  };
}

/** Pure: live payload -> snapshot. Only allow-listed fields are copied. */
export function toFallbackSnapshot(payload: MenuPayload, generatedAt: Date): MenuFallback {
  return {
    generatedAt: generatedAt.toISOString(),
    categories: payload.categories.map(pickCategory),
    settings: pickSettings(payload.settings),
    note: FALLBACK_NOTE,
  };
}

/** Every key that may appear anywhere in the snapshot. Anything else is a leak and stops the export. */
const ALLOWED_KEYS = new Set([
  // top level
  "generatedAt", "categories", "settings", "note",
  // settings
  "hours", "weekly", ...DAYS, "open", "close", "closures", "date", "label",
  "announcement", "pricesIncludeVat", "serviceChargePct", "vatPct",
  // categories, items, variants
  "id", "slug", "name", "sortOrder", "items", "categoryId", "description", "price", "diet", "tags", "isSoldOut",
  "imageUrl", "imageVariants", "variants", "kind", "priceDelta",
  // 1.4.0: checked by assertTranslations below, not by the generic walk
  "translations",
]);

/** Inside `translations` only: language keys, then the per-language text fields (strings only). */
const TRANSLATION_LANG_KEYS = new Set<string>(MENU_TRANSLATION_LANGS);
const TRANSLATION_FIELDS = new Set(["name", "description", "pronunciation", "label"]);

function assertTranslations(value: unknown, path: string): void {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new FallbackExportError(`Refusing to write the snapshot: "translations" at ${path} is not an object.`);
  }
  for (const [lang, entry] of Object.entries(value)) {
    if (!TRANSLATION_LANG_KEYS.has(lang)) {
      throw new FallbackExportError(`Refusing to write the snapshot: unexpected key "${lang}" at ${path}.`);
    }
    if (!entry || typeof entry !== "object" || Array.isArray(entry)) {
      throw new FallbackExportError(`Refusing to write the snapshot: ${path}.${lang} is not an object.`);
    }
    for (const [k, v] of Object.entries(entry)) {
      if (!TRANSLATION_FIELDS.has(k) || typeof v !== "string") {
        throw new FallbackExportError(`Refusing to write the snapshot: unexpected key "${k}" at ${path}.${lang}.`);
      }
    }
  }
}

export function assertOnlyAllowedKeys(value: unknown, path = "$"): void {
  if (Array.isArray(value)) {
    value.forEach((v, i) => assertOnlyAllowedKeys(v, `${path}[${i}]`));
    return;
  }
  if (value && typeof value === "object") {
    for (const [k, v] of Object.entries(value)) {
      if (!ALLOWED_KEYS.has(k)) throw new FallbackExportError(`Refusing to write the snapshot: unexpected key "${k}" at ${path}.`);
      if (k === "translations") assertTranslations(v, `${path}.${k}`);
      else assertOnlyAllowedKeys(v, `${path}.${k}`);
    }
  }
}

export function snapshotStats(s: MenuFallback): FallbackStats {
  const items = s.categories.flatMap((c) => c.items);
  return {
    categories: s.categories.length,
    items: items.length,
    variants: items.reduce((n, it) => n + it.variants.length, 0),
  };
}

/**
 * True if the key is NOT an anon/publishable key (service role JWT or a `sb_secret_` key). The export must read
 * with the anon key so RLS decides what is public; a privileged key would bypass RLS.
 */
export function keyLooksPrivileged(key: string): boolean {
  const k = key.trim();
  if (k.startsWith("sb_secret_")) return true;
  const parts = k.split(".");
  if (parts.length !== 3 || !parts[1]) return false;
  try {
    const b64 = parts[1].replace(/-/g, "+").replace(/_/g, "/");
    const payload = JSON.parse(atob(b64.padEnd(b64.length + ((4 - (b64.length % 4)) % 4), "="))) as { role?: unknown };
    return payload?.role === "service_role";
  } catch {
    return false;
  }
}

/**
 * Read the live public menu with the given (anon) client and build the snapshot.
 * Throws AppError INTERNAL (from getPublicMenu) when the database cannot be read, and FallbackExportError when the
 * result is empty (unless `allowEmpty`) or would contain a key outside the allow-list.
 */
export async function exportMenuFallback(
  db: Db,
  opts: { now?: Date; allowEmpty?: boolean } = {},
): Promise<{ snapshot: MenuFallback; json: string; stats: FallbackStats }> {
  const now = opts.now ?? new Date();
  // supabaseUrl "" on purpose: image URLs are stripped from the snapshot anyway.
  const payload = await getPublicMenu(db, "", now);
  const snapshot = toFallbackSnapshot(payload, now);
  assertOnlyAllowedKeys(snapshot);
  const stats = snapshotStats(snapshot);
  if (stats.items === 0 && !opts.allowEmpty) {
    throw new FallbackExportError(
      "The live menu has no visible items, so the snapshot was NOT written (an empty break-glass menu helps nobody). " +
        "Check that the env points at the right Supabase project, or pass --allow-empty to write it anyway.",
    );
  }
  return { snapshot, json: `${JSON.stringify(snapshot, null, 2)}\n`, stats };
}
